// ---------------- bahasa aktif ----------------
function detect() {
  try {
    const q = new URLSearchParams(location.search).get('lang');
    if (q === 'id' || q === 'en') return q;
  } catch {}
  try {
    const s = localStorage.getItem('gold24k-lang');
    if (s === 'id' || s === 'en') return s;
  } catch {}
  return (navigator.language || 'id').toLowerCase().startsWith('id') ? 'id' : 'en';
}

let lang = detect();
export const getLang = () => lang;

export function t(key, vars) {
  let s = STR[lang][key] ?? STR.id[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}

// isi semua teks statis di halaman
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.desc'));
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
  }
  for (const b of root.querySelectorAll('[data-lang]')) b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
}

export function setLang(next) {
  if (next !== 'id' && next !== 'en') return;
  lang = next;
  try {
    localStorage.setItem('gold24k-lang', next);
  } catch {}
  try {
    const u = new URL(location.href);
    if (u.searchParams.has('lang')) {
      u.searchParams.set('lang', next);
      history.replaceState(null, '', u);
    }
  } catch {}
  applyStatic();
  document.dispatchEvent(new CustomEvent('langchange', { detail: next }));
}

// ---------------- format angka & waktu ----------------
const cache = new Map();
const memo = (key, make) => {
  if (!cache.has(key)) cache.set(key, make());
  return cache.get(key);
};
const numLocale = () => (lang === 'en' ? 'en-US' : 'id-ID');
const nf = (min, max) =>
  memo(`n|${lang}|${min}|${max}`, () => new Intl.NumberFormat(numLocale(), { minimumFractionDigits: min, maximumFractionDigits: max }));
const dtf = (opts, tz = 'UTC') =>
  memo(`d|${lang}|${tz}|${JSON.stringify(opts)}`, () => new Intl.DateTimeFormat(lang === 'en' ? 'en-US' : 'id-ID', { timeZone: tz, ...opts }));
const ok = (n) => n != null && isFinite(n);
const dateMs = (d) => (typeof d === 'number' ? d : Date.parse(d + 'T00:00:00Z'));

export const fmt = {
  num: (n, min = 0, max = min) => (ok(n) ? nf(min, max).format(n) : '–'),
  idr: (n) => (!ok(n) ? '–' : lang === 'en' ? `IDR ${nf(0, 0).format(Math.round(n))}` : `Rp${nf(0, 0).format(Math.round(n))}`),
  usd: (n, d = 2) => (!ok(n) ? '–' : lang === 'en' ? `$${nf(d, d).format(n)}` : `US$${nf(d, d).format(n)}`),
  pct: (p) => (!ok(p) ? '–' : Math.abs(p) < 0.005 ? `${nf(2, 2).format(0)}%` : `${p > 0 ? '+' : '−'}${nf(2, 2).format(Math.abs(p))}%`),
  pctAbs: (p) => `${nf(2, 2).format(Math.abs(p))}%`,
  signed: (n, f) => `${n > 0 ? '+' : n < 0 ? '−' : ''}${f(Math.abs(n))}`,
  time: (ms) =>
    memo(`t|${lang}`, () =>
      new Intl.DateTimeFormat(lang === 'en' ? 'en-GB' : 'id-ID', { timeZone: 'Asia/Jakarta', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }),
    ).format(ms),
  date: (d) => dtf({ weekday: 'short', day: 'numeric', month: 'short' }).format(dateMs(d)),
  dateLong: (d) => dtf({ weekday: 'long', day: 'numeric', month: 'long' }).format(dateMs(d)),
  dateShort: (d) => dtf({ day: 'numeric', month: 'short' }).format(dateMs(d)),
  dateYear: (d) => dtf({ day: 'numeric', month: 'short', year: 'numeric' }).format(dateMs(d)),
  dateTimeWib: (ms) => dtf({ day: 'numeric', month: 'short' }, 'Asia/Jakarta').format(ms),
  rel(ms) {
    const s = (Date.now() - ms) / 1000;
    if (s < 60) return t('time.justNow');
    if (s < 3600) return t('time.min', { n: Math.floor(s / 60) });
    if (s < 86400) return t('time.hour', { n: Math.floor(s / 3600) });
    return t('time.day', { n: Math.floor(s / 86400) });
  },
  dur(ms) {
    const m = Math.max(0, Math.round(ms / 60000));
    const h = Math.floor(m / 60);
    const d = Math.floor(h / 24);
    if (d >= 1) return t('dur.dh', { d, h: h % 24 });
    return h ? t('dur.hm', { h, m: m % 60 }) : t('dur.m', { m });
  },
};
